    def calculate_houses(self, year: int, month: int, day: int,
                         hour: int, minute: int, lat: float, lng: float,
                         tz_offset: float = 0) -> Dict[str, Any]:
        """
        使用swisseph直接计算四轴和宫位
        参数：tz_offset - 时区偏移（小时数），例如：8表示UTC+8
        返回：cusps, ascmc, axes_info
        """
        # 使用传入的时区偏移，不再硬编码中国时区
        # 转换为UTC时间
        utc_hour = hour - tz_offset
        utc_time = utc_hour + minute / 60

        # 计算儒略日
        jd = swe.julday(year, month, day, utc_time)

        # 计算普拉西度宫位 (b'P' = Placidus)
        cusps, ascmc = swe.houses(jd, lat, lng, b'P')

        # 计算四轴
        asc_lon = ascmc[0] % 360
        mc_lon = ascmc[1] % 360
        desc_lon = (asc_lon + 180) % 360
        ic_lon = (mc_lon + 180) % 360

        # 构建四轴信息
        axes_info = {
            "ascendant": self._create_axis_info(asc_lon, "ascendant"),
            "midheaven": self._create_axis_info(mc_lon, "midheaven"),
            "descendant": self._create_axis_info(desc_lon, "descendant"),
            "imum_coeli": self._create_axis_info(ic_lon, "imum_coeli")
        }

        return {
            "cusps": cusps,
            "ascmc": ascmc,
            "axes": axes_info,
            "jd": jd,
            "utc_time": utc_time,
            "tz_offset": tz_offset
        }

    def _parse_timezone_offset(self, tz_str: str, year: int, month: int, day: int,
                               hour: int = 12, minute: int = 0) -> float:
        """
        将时区字符串转换为小时偏移，含夏令时。
        中国时区（Asia/Shanghai/Hong_Kong/Taipei）1986-1991 使用精确历史数据（精确到小时）；
        其余时区及 UTC±xx:xx 格式统一用 zoneinfo 精确计算。
        """
        try:
            # ── UTC 字面格式：UTC+08:00 / UTC-05:00 ──
            if tz_str.startswith('UTC'):
                sign = 1 if '+' in tz_str else -1
                parts = tz_str.split('+') if '+' in tz_str else tz_str.split('-')
                time_part = parts[1] if len(parts) > 1 else '0'
                if ':' in time_part:
                    h, m = time_part.split(':')
                    base_offset = sign * (float(h) + float(m) / 60.0)
                else:
                    base_offset = sign * float(time_part)
                return self._apply_daylight_saving(base_offset, tz_str, year, month, day, hour, minute)

            # ── IANA 时区字符串：全部用 zoneinfo ──
            # _apply_daylight_saving 已经内含 zoneinfo 逻辑，直接传 0 作为 base
            # 但中国历史夏令时需要 base_offset=8，所以先判断
            china_zones = ("Asia/Shanghai", "Asia/Hong_Kong", "Asia/Taipei", "Asia/Macau")
            if tz_str in china_zones:
                return self._apply_daylight_saving(8.0, tz_str, year, month, day, hour, minute)

            # 其他所有 IANA 时区：直接用 zoneinfo 读精确时刻偏移
            from datetime import datetime
            tz = ZoneInfo(tz_str)
            dt = datetime(year, month, day, hour, minute, tzinfo=tz)
            # 检测春拨跳过时段（fold=0 和 fold=1 偏移不同说明该时刻不存在）
            dt_fold = dt.replace(fold=1)
            if dt.utcoffset() != dt_fold.utcoffset():
                # 出生时刻落在春拨空白段，用 fold=1（拨后侧）更符合实际
                dt = dt_fold
            return dt.utcoffset().total_seconds() / 3600

        except Exception:
            return 0.0

    def _apply_daylight_saving(self, base_offset: float, tz_str: str, year: int, month: int, day: int,
                                hour: int = 12, minute: int = 0) -> float:
        """
        应用夏令时调整，返回调整后的时区偏移（小时）。

        中国时区（Asia/Shanghai / Asia/Hong_Kong / Asia/Taipei）使用精确历史数据，
        切换时刻为当地时间 02:00（与 IANA tzdata PRC 规则一致）：
          - 开始日：02:00 前为标准时，02:00 起进入夏令时（时钟拨快1小时）
          - 结束日：02:00 前仍为夏令时，02:00 起恢复标准时（时钟拨慢1小时）
        其余时区统一使用 zoneinfo（IANA 数据库）精确计算，支持全球所有夏令时规则。
        """
        # ── 中国夏令时（1986-1991，精确到小时）──
        if tz_str in ("Asia/Shanghai", "Asia/Hong_Kong", "Asia/Taipei") and 1986 <= year <= 1991:
            china_dst_dates = {
                # (开始月日, 结束月日)  — 均为 02:00 本地时间切换
                1986: ((5,  4), (9, 14)),
                1987: ((4, 12), (9, 13)),
                1988: ((4, 17), (9, 11)),
                1989: ((4, 16), (9, 17)),
                1990: ((4, 15), (9, 16)),
                1991: ((4, 14), (9, 15)),
            }
            if year in china_dst_dates:
                dst_start, dst_end = china_dst_dates[year]
                sm, sd = dst_start   # 开始月、日
                em, ed = dst_end     # 结束月、日

                # 是否在开始时刻之后（开始日当天须 >= 02:00）
                after_start = (
                    month > sm or
                    (month == sm and day > sd) or
                    (month == sm and day == sd and hour >= 2)
                )
                # 是否在结束时刻之前（结束日当天须 < 02:00）
                before_end = (
                    month < em or
                    (month == em and day < ed) or
                    (month == em and day == ed and hour < 2)
                )

                if after_start and before_end:
                    return base_offset + 1.0
            return base_offset

        # ── 其他所有时区：使用 zoneinfo 精确计算 ──
        try:
            from datetime import datetime
            tz = ZoneInfo(tz_str)
            dt = datetime(year, month, day, hour, minute, tzinfo=tz)  # 精确时刻
            return dt.utcoffset().total_seconds() / 3600
        except Exception:
            return base_offset

