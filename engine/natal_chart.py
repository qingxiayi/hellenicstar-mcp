            from hellenistic import is_diurnal
            is_day = is_diurnal(sun_lon, asc_lon)
            if is_day:
                fof_lon = (asc_lon + moon_lon - sun_lon) % 360
                pos_lon = (asc_lon + sun_lon - moon_lon) % 360
            else:
                fof_lon = (asc_lon + sun_lon - moon_lon) % 360
                pos_lon = (asc_lon + moon_lon - sun_lon) % 360
            
            fof_sign_num = int(fof_lon // 30)
