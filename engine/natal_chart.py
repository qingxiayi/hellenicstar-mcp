            # 检查城市是否在本地坐标映射中（多轮模糊匹配）
            lookup_city = city.strip()
            
            # 轮1：原名
            if lookup_city not in self.CITY_COORDINATES:
                # 轮2：去掉「市/县/区/省/自治州/自治县」后缀
                for suffix in ['市', '县', '区', '省', '自治州', '自治县', '特别行政区']:
                    if lookup_city.endswith(suffix):
                        stripped = lookup_city[:-len(suffix)]
                        if stripped in self.CITY_COORDINATES:
                            lookup_city = stripped
                            break
            
            if lookup_city not in self.CITY_COORDINATES:
                # 轮3：去掉「XX族自治县/XX族自治州」等民族自治后缀
                import re as _re
                stripped = _re.sub(r'[族回壮苗彝满蒙藏维哈侗布依土家瑶白傣黎傈僳佤拉祜纳西景颇柯尔克孜仡佬东乡撒拉保安裕固锡伯阿昌普米怒鄂温克崩龙德昂独龙鄂伦春赫哲门巴珞巴基诺水仫佬毛南京广]+自治[州县旗]$', '', lookup_city)
                if stripped and stripped in self.CITY_COORDINATES:
                    lookup_city = stripped
            
            if lookup_city not in self.CITY_COORDINATES:
                # 轮4：前2字匹配（如「三台县」→「三台」）
                if len(city.strip()) >= 3:
                    prefix2 = city.strip()[:2]
                    if prefix2 in self.CITY_COORDINATES:
                        lookup_city = prefix2

            # 解析坐标 + 时区原料 tz_raw：resolved（新链 EngineAdapter）优先；
            # 否则走 city 查表（旧链，将随地理重构退役）。
            if resolved is not None:
                lat = float(resolved["lat"])
                lng = float(resolved["lng"])
                # 数字偏移 → 复用下方「float UTC offset」分支：tz_str="UTC" + UTC 挂钟，
                # 与 swisseph 同喂同一个 UTC 瞬间（plan §5.3 单一瞬间不变量）。
                tz_raw = float(resolved["utc_offset"])
                _coords_ok = True
            elif lookup_city in self.CITY_COORDINATES:
                # 使用本地坐标映射，避免geonames查询
                lat, lng = self.CITY_COORDINATES[lookup_city]
                # 根据城市设置时区
                tz_raw = self._get_timezone_for_city(lookup_city, country_code)
                _coords_ok = True
            else:
                _coords_ok = False

            if _coords_ok:
                from datetime import datetime as _dtc, timedelta as _tdc

                # ── float UTC offset（前端直接传 tz 数字，如 2.0 = UTC+2）──
                if isinstance(tz_raw, (int, float)):
                    dst_offset  = float(tz_raw)
                    base_offset = dst_offset   # 前端已含夏令时，无需二次调整
                    tz_str      = "UTC"        # kerykeion 用 UTC 模式，输入时间转为 UTC
                    # 将本地时间转换为 UTC（减去偏移）
                    _base_dt = _dtc(year, month, day, hour, minute)
                    _adj_dt  = _base_dt - _tdc(hours=dst_offset)
                    adj_year, adj_month, adj_day = _adj_dt.year, _adj_dt.month, _adj_dt.day
                    adj_hour   = _adj_dt.hour
                    adj_minute = _adj_dt.minute
                else:
                    # ── 正常 IANA 时区字符串路径 ──
                    tz_str = tz_raw
                    # 夏令时调整：kerykeion 不自动处理历史夏令时
                    # _parse_timezone_offset 已含 zoneinfo 精确计算，直接用
                    # 目的：把用户输入的本地时间转换为 kerykeion 需要的「无夏令时本地时间」
                    dst_offset = self._parse_timezone_offset(tz_str, year, month, day, hour, minute)
                    # 标准时偏移（无夏令时）：
                    # 北半球取1月，南半球（澳洲/新西兰/南美/南非）取7月
