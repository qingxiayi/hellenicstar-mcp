    def _calculate_lunations(self, birth_jd: float) -> Dict[str, Any]:
        """计算出生前后新月满月，日月食标注，合并去重。"""
        signs = ['白羊','金牛','双子','巨蟹','狮子','处女',
                 '天秤','天蝎','射手','摩羯','水瓶','双鱼']

        def _sm_angle(jd):
            s = swe.calc_ut(jd, swe.SUN, swe.FLG_SWIEPH)[0][0]
            m = swe.calc_ut(jd, swe.MOON, swe.FLG_SWIEPH)[0][0]
            return (m - s) % 360

        def _bisect(jd1, jd2, target):
            for _ in range(30):
                mid = (jd1 + jd2) / 2
                a = _sm_angle(mid)
                diff = (a - target + 180) % 360 - 180
                if abs(diff) < 0.0001: return mid
                if diff > 0: jd2 = mid
                else: jd1 = mid
            return (jd1 + jd2) / 2

        # ── Step 1: 用 eclipse API 找 4 个最近的日月食 ──
        eclipses_jd = []  # [(jd, type, lunar_type)]

        def _add_eclipse(jd, prefix, flags, is_solar):
            p = []
            if is_solar:
                if flags & swe.ECL_TOTAL: p.append('全')
                if flags & swe.ECL_ANNULAR: p.append('环')
                if flags & swe.ECL_PARTIAL: p.append('偏')
            else:
                if flags & swe.ECL_TOTAL: p.append('全')
                if flags & swe.ECL_PARTIAL: p.append('偏')
                if flags & swe.ECL_PENUMBRAL: p.append('半影')
            ecl_t = '+'.join(p)
            eclipses_jd.append((jd, f'{prefix}{ecl_t}食', '新月' if is_solar else '满月'))

        # 日食
        rf, tr = swe.sol_eclipse_when_glob(birth_jd, swe.FLG_SWIEPH, 0, True)
        rf2, _, _ = swe.sol_eclipse_where(tr[0], swe.FLG_SWIEPH)
        _add_eclipse(tr[0], '日', rf2, True)

        rf, tr = swe.sol_eclipse_when_glob(birth_jd, swe.FLG_SWIEPH, 0, False)
        rf2, _, _ = swe.sol_eclipse_where(tr[0], swe.FLG_SWIEPH)
        _add_eclipse(tr[0], '日', rf2, True)

        # 月食
        rf, tr = swe.lun_eclipse_when(birth_jd, swe.FLG_SWIEPH, 0, True)
        _add_eclipse(tr[0], '月', rf, False)

        rf, tr = swe.lun_eclipse_when(birth_jd, swe.FLG_SWIEPH, 0, False)
        _add_eclipse(tr[0], '月', rf, False)

        # ── Step 2: 扫描 ±120 天新月满月 ──
        lunations = {}  # round(jd,2) → event

        jd = birth_jd - 130
        end = birth_jd + 130
        # 步长 0.5 天：日月角以 ~12.2°/天单调增，最快约 14.4°/天（近地点），
        # 单步最大跨 ~7.2° « 检测窗（新月要求 prev>330 且 cur<30，容差 30°），
        # 绝不漏跨；跨点仍落在 [jd-step, jd] 内由 _bisect 收敛到 1e-4 天精度。
        # 相比旧的 1/24 天（1h）少 ~6.5× swisseph 调用（~385ms→~60ms）。
        # 边界(±130天)最远月相在粗步下可能微抖，但显示只取最近食相(来自 eclipse API)
        # + 最近常规月相(~15天，远离边界)，216 盘端到端对拍显示结果 0 差异。
        step = 0.5
        prev = _sm_angle(jd)
        jd += step

        while jd < end:
            cur = _sm_angle(jd)
            # 新月
            if prev > 330 and cur < 30:
                ejd = _bisect(jd - step, jd, 0)
                key = round(ejd, 2)
                if key not in lunations:
                    mlon = swe.calc_ut(ejd, swe.MOON, swe.FLG_SWIEPH)[0][0]
                    si = int(mlon // 30) % 12
                    y, m, d, _ = swe.revjul(ejd)
                    days_exact = ejd - birth_jd
                    days = round(days_exact) if abs(days_exact) >= 0.5 else (1 if days_exact > 0 else -1 if days_exact < 0 else 0)
                    # 检查是否为日月食 (JD 差 <0.4天)
                    ecl_label = None
                    for ejd0, etype, _ in eclipses_jd:
                        if abs(ejd - ejd0) < 0.4:
                            ecl_label = etype
                            break
                    lt = '新月'
                    lunations[key] = {
                        'jd': ejd,
                        'date': f'{y}年{m}月{d}日', 'lunar_type': lt,
                        'eclipse': ecl_label, 'label': ecl_label if ecl_label else lt,
                        'sign_cn': signs[si], 'degree': round(mlon % 30, 1),
                        'days': days_exact,
                        'days_int': days,
                    }
            # 满月
            if prev < 180 and cur > 180:
                ejd = _bisect(jd - step, jd, 180)
                key = round(ejd, 2)
                if key not in lunations:
                    mlon = swe.calc_ut(ejd, swe.MOON, swe.FLG_SWIEPH)[0][0]
                    si = int(mlon // 30) % 12
                    y, m, d, _ = swe.revjul(ejd)
                    days_exact = ejd - birth_jd
                    days = round(days_exact) if abs(days_exact) >= 0.5 else (1 if days_exact > 0 else -1 if days_exact < 0 else 0)
                    ecl_label = None
                    for ejd0, etype, _ in eclipses_jd:
                        if abs(ejd - ejd0) < 0.4:
                            ecl_label = etype
                            break
                    lt = '满月'
                    lunations[key] = {
                        'jd': ejd,
                        'date': f'{y}年{m}月{d}日', 'lunar_type': lt,
                        'eclipse': ecl_label, 'label': ecl_label if ecl_label else lt,
                        'sign_cn': signs[si], 'degree': round(mlon % 30, 1),
                        'days': days_exact,
                        'days_int': days,
                    }
            prev = cur
            jd += step

        # ── Step 3: 未被扫描覆盖的日月食单独补入 ──
        for ejd0, etype, lt in eclipses_jd:
            # 检查是否和已有月相重复 (JD 差 <0.4天)
            dup = False
            for v in lunations.values():
                if abs(v['jd'] - ejd0) < 0.4:
                    dup = True
                    break
            if dup:
                continue
            key = round(ejd0, 2)
            if key not in lunations:
                days_exact = ejd0 - birth_jd
                days = round(days_exact) if abs(days_exact) >= 0.5 else (1 if days_exact > 0 else -1 if days_exact < 0 else 0)
                mlon = swe.calc_ut(ejd0, swe.MOON, swe.FLG_SWIEPH)[0][0]
                si = int(mlon // 30) % 12
                y, m, d, _ = swe.revjul(ejd0)
                lunations[key] = {
                    'jd': ejd0,
                    'date': f'{y}年{m}月{d}日',
                    'lunar_type': lt,
                    'eclipse': etype, 'label': etype,
                    'sign_cn': signs[si], 'degree': round(mlon % 30, 1),
                    'days': days_exact,
                    'days_int': days,
                }

        all_luns = sorted(lunations.values(), key=lambda x: abs(x['days']))
        before = [l for l in all_luns if l['days'] < 0]
        after  = [l for l in all_luns if l['days'] > 0]

        return {
            'all': all_luns,
            'closest_before': before[0] if before else None,
            'closest_after': after[0] if after else None,
        }

