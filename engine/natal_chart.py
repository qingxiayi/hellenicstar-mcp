            special_points = {}
            # ── 北交点：直接用 swisseph TRUE_NODE，精度高于 kerykeion 封装 ──
            try:
                import swisseph as swe
                utc_time_node = (hour - tz_offset) + minute / 60.0
                jd_node = swe.julday(year, month, day, utc_time_node)
                node_result = swe.calc_ut(jd_node, swe.MEAN_NODE)
                node_lon = node_result[0][0]
                node_retrograde = node_result[0][3] < 0  # 速度为负 = 逆行
                node_sign_num = int(node_lon // 30)
                node_sign = self.ZODIAC_ABBRS[node_sign_num]
                special_points["true_north_lunar_node"] = {
                    "sign": node_sign,
                    "sign_zh": self.SIGNS_ZH.get(node_sign, node_sign),
                    "position": node_lon - node_sign_num * 30,
                    "longitude": node_lon,
                    "retrograde": node_retrograde,
                    "house": self.get_planet_house(node_lon, cusps)
                }
            except Exception as e:
                # swisseph 失败则回退 kerykeion
                print(f"Warning: swisseph TRUE_NODE failed, falling back to kerykeion: {e}")
                for point_name in ["true_north_lunar_node"]:
                    point_obj = getattr(subject, "true_north_lunar_node", None)
                    if point_obj is None:
                        point_obj = subject.get("true_node") if hasattr(subject, 'get') else getattr(subject, "true_node", None)
                    if point_obj:
                        point_info = self.get_planet_info(point_obj)
                        if point_info:
                            point_info["house"] = self.get_planet_house(point_info["longitude"], cusps)
                            special_points[point_name] = point_info

            # 手动用瑞士星历表计算凯龙星（swe.CHIRON = 15）
            try:
                import swisseph as swe
                # 计算儒略日（jd 在函数体内未定义，需要在此计算）
                utc_hour = hour - tz_offset
                utc_time = utc_hour + minute / 60.0
                jd = swe.julday(year, month, day, utc_time)
                chiron_result = swe.calc_ut(jd, swe.CHIRON)
                chiron_lon = chiron_result[0][0] if chiron_result and len(chiron_result) > 0 else 0
                chiron_retrograde = chiron_result[0][3] < 0 if chiron_result and len(chiron_result) > 0 else False
                sign_num = int(chiron_lon // 30)
                sign = self.ZODIAC_ABBRS[sign_num]
                position = chiron_lon - (sign_num * 30)
                special_points["chiron"] = {
                    "sign": sign,
                    "sign_zh": self.SIGNS_ZH.get(sign, sign),
                    "position": position,
                    "longitude": chiron_lon,
                    "retrograde": chiron_retrograde,
                    "house": self.get_planet_house(chiron_lon, cusps)
                }
            except Exception as e:
                print(f"Warning: Failed to calculate Chiron: {e}")

