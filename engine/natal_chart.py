            special_points["part_of_spirit"] = {
                "sign": pos_sign,
                "sign_zh": self.SIGNS_ZH.get(pos_sign, pos_sign),
                "position": pos_lon - pos_sign_num * 30,
                "longitude": pos_lon,
                "retrograde": False,
                "house": self.get_planet_house(pos_lon, cusps)
            }

            # ── 新月满月 + 日月食 ──
            lunations = self._calculate_lunations(houses_result["jd"])

            # 计算月相
            moon_phase = self.calculate_moon_phase(
                planets["sun"]["longitude"],
                planets["moon"]["longitude"]
            )

            # 准备所有点用于相位计算
            all_points = []
            # 添加行星
            for name, info in planets.items():
                if info:
                    # 创建模拟的行星对象
                    class MockPlanet:
                        def __init__(self, info):
                            self.abs_pos = info["longitude"]
                            self.sign = info["sign"]
                            self.position = info["position"]
